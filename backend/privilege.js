'use strict';

/**
 * Single-elevation privilege helper.
 *
 * Rufus needs root for every step of a write operation: unmounting, wiping the
 * partition table, partitioning, formatting and the actual data transfer. The
 * previous implementation shelled out to `pkexec` once per command, which meant
 * the polkit agent asked for the password half a dozen times for a single flash
 * and the (synchronous) `execSync` calls froze the UI while the dialog was up.
 *
 * This module instead runs one generated bash script through one `pkexec`
 * invocation, so a write operation = one authentication. Progress and errors
 * travel back over stdout through `##RUFUS:` markers, and cancellation is
 * cooperative: the unprivileged renderer touches a flag file that the root
 * script polls (a plain user cannot signal root-owned processes).
 */

const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');

const { shellQuote } = require('./shell');

const MARKER = '##RUFUS:';
const ERROR_MARKER = '##RUFUS-ERROR:';
const STATE_DIR = path.join('/tmp', `rufus-linux-${process.getuid ? process.getuid() : 1000}`);
const SCRIPT_PATH = path.join(STATE_DIR, 'operation.sh');
const CANCEL_PATH = path.join(STATE_DIR, 'cancel');
const OUTPUT_PATH = path.join(STATE_DIR, 'output.log');

let activeRun = null;

function ensureStateDir() {
  fs.mkdirSync(STATE_DIR, { recursive: true, mode: 0o700 });
  try {
    fs.chmodSync(STATE_DIR, 0o700);
  } catch (e) {
    // best effort
  }
}

/**
 * Build a line that emits a progress marker from the generated script. The JSON
 * payload is single-quoted, so it can carry any character the UI cares to send.
 */
function marker(payload) {
  return `emit ${shellQuote(JSON.stringify(payload))}`;
}

/**
 * Shell prelude shared by every privileged script: deterministic environment,
 * marker helper, cancel-flag helper and a guaranteed cleanup hook.
 */
function buildPreamble(extra = {}) {
  const vars = Object.entries({ RUFUS_CANCEL: CANCEL_PATH, RUFUS_TMP: STATE_DIR, ...extra })
    .map(([key, value]) => `${key}=${shellQuote(value)}`)
    .join('\n');

  return `#!/bin/bash
# Generated by rufus-linux. Runs as root through a single pkexec transaction.
set -uo pipefail
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
export LC_ALL=C
umask 077

${vars}

emit() {
  printf '%s\\n' ${shellQuote(MARKER + '"')}"$1"
}

fail() {
  printf '%s\\n' ${shellQuote(ERROR_MARKER)}"$(printf '%s' "$1" | tr '\\n' ' ')"
  exit 1
}

log() {
  printf '%s\\n' "$*" >> "$RUFUS_TMP/output.log" 2>/dev/null || true
}

cancelled() {
  [ -e "$RUFUS_CANCEL" ]
}
`;
}

/**
 * Poll a background command, forwarding progress lines and honouring the
 * cancel flag. Runs the loop in bash because only the root script is allowed to
 * signal its own children.
 *
 * $1  progress log file (command stderr is written here)
 * $2  byte total used to turn "N bytes" into a percentage (0 disables)
 * $3  command to run
 */
const RUN_WITH_PROGRESS = `
run_with_progress() {
  local logfile="$1" total="$2"; shift 2
  local child=0 line bytes percent

  "$@" 2>"$logfile" &
  child=$!

  while kill -0 "$child" 2>/dev/null; do
    if cancelled; then
      kill -TERM "$child" 2>/dev/null
      wait "$child" 2>/dev/null
      emit '{"stage":"cancelled","message":"Cancelled","percent":0}'
      exit 130
    fi
    if [ -s "$logfile" ]; then
      line="$(tr '\\r' '\\n' < "$logfile" | tail -n 1)"
      bytes="$(printf '%s' "$line" | sed -n 's/^[^0-9]*\\([0-9][0-9]*\\) bytes.*/\\1/p')"
      if [ -n "$bytes" ] && [ "$total" -gt 0 ] 2>/dev/null; then
        percent=$(( bytes * 100 / total ))
        [ "$percent" -gt 99 ] && percent=99
        emit "{\\"stage\\":\\"progress\\",\\"percent\\":$percent,\\"detail\\":\\"$bytes bytes written\\"}"
      fi
    fi
    sleep 0.4
  done

  wait "$child"
  return $?
}

# Same loop without progress parsing: used for wimlib/format steps where we
# only care about honouring cancellation.
run_cancellable() {
  local child=0
  "$@" &
  child=$!
  while kill -0 "$child" 2>/dev/null; do
    if cancelled; then
      kill -TERM "$child" 2>/dev/null
      wait "$child" 2>/dev/null
      emit '{"stage":"cancelled","message":"Cancelled","percent":0}'
      exit 130
    fi
    sleep 0.4
  done
  wait "$child"
  return $?
}

# Run a command that reports its own "NN%" progress (wimlib does) and map that
# onto a slice of the overall progress bar.
# $1 output log, $2 base percent, $3 span percent, rest: command
run_with_percent() {
  local logfile="$1" base="$2" span="$3"; shift 3
  local child=0 line pct value
  ": > "$logfile"
  "$@" >"$logfile" 2>&1 &
  child=$!
  while kill -0 "$child" 2>/dev/null; do
    if cancelled; then
      kill -TERM "$child" 2>/dev/null
      wait "$child" 2>/dev/null
      emit '{"stage":"cancelled","message":"Cancelled","percent":0}'
      exit 130
    fi
    line="$(tr '\\r' '\\n' < "$logfile" 2>/dev/null | tail -n 1)"
    pct="$(printf '%s' "$line" | sed -n 's/.*[^0-9]\\([0-9]\\{1,3\\}\\)%.*/\\1/p')"
    if [ -n "$pct" ]; then
      value=$(( base + pct * span / 100 ))
      [ "$value" -gt 99 ] && value=99
      line="\${line//[^A-Za-z0-9 .:%()\\/,-]/ }"
      emit "{\\"stage\\":\\"progress\\",\\"percent\\":$value,\\"detail\\":\\"$line\\"}"
    fi
    sleep 0.5
  done
  wait "$child"
  return $?
}

# /dev/sdb -> /dev/sdb1, /dev/nvme0n1 -> /dev/nvme0n1p1, /dev/mmcblk0 -> /dev/mmcblk0p1
part_dev() {
  case "$1" in
    *nvme*n*|*mmcblk*) printf '%sp%s' "$1" "$2" ;;
    *) printf '%s%s' "$1" "$2" ;;
  esac
}

# Unmount the device itself and every partition it exposes.
unmount_device() {
  local dev="$1" node mountpoint
  for node in "$dev" "$dev"?*; do
    [ -e "$node" ] || continue
    mountpoint="$(lsblk -n -o MOUNTPOINT "$node" 2>/dev/null | sed 's/[[:space:]]//g' | grep -v '^$' | head -n 1)"
    if [ -n "$mountpoint" ]; then
      umount "$mountpoint" 2>/dev/null || umount -l "$mountpoint" 2>/dev/null || true
    fi
  done
}

# The kernel needs a moment to publish freshly created partitions.
wait_for_partition() {
  local node="$1" tries=40
  while [ "$tries" -gt 0 ]; do
    [ -b "$node" ] && return 0
    partprobe "$node" >/dev/null 2>&1 || true
    udevadm settle >/dev/null 2>&1 || true
    sleep 0.25
    tries=$(( tries - 1 ))
  done
  [ -b "$node" ]
}

# Fail early (before anything is erased) when a helper program is missing.
require_tools() {
  local tool missing=""
  for tool in "$@"; do
    command -v "$tool" >/dev/null 2>&1 || missing="$missing $tool"
  done
  if [ -n "$missing" ]; then
    fail "Missing required tool(s):$missing. Install them and try again."
  fi
}

mount_point() {
  local path="$1"
  if ! mount "$path" 2>>"$RUFUS_TMP/output.log"; then
    fail "Could not mount $path"
  fi
}
`;

/**
 * Run a privileged script.
 *
 * @param {object}   options
 * @param {string}   options.body    bash body appended after the preamble
 * @param {object}   options.vars    extra environment values baked into the script
 * @param {Function} options.onProgress called with each parsed marker payload
 * @param {boolean}  options.helpers  include the progress/cancel helper functions
 * @returns {Promise<{code:number, stdout:string}>}
 */
function runPrivileged({ body, vars = {}, onProgress = () => {}, helpers = true }) {
  ensureStateDir();
  clearCancel();
  fs.writeFileSync(OUTPUT_PATH, '');

  const script = buildPreamble(vars) + (helpers ? RUN_WITH_PROGRESS : '\n') + body;
  fs.writeFileSync(SCRIPT_PATH, script, { mode: 0o700 });

  return new Promise((resolve, reject) => {
    let stdout = '';
    let stderr = '';
    let errorText = null;
    let cancelledByUser = false;

    const child = spawn('pkexec', ['--disable-internal-agent', '/bin/bash', SCRIPT_PATH], {
      stdio: ['ignore', 'pipe', 'pipe'],
      detached: false
    });

    activeRun = child;

    // stdout arrives in arbitrary chunks, so a marker can be split across two
    // reads. Keep the incomplete tail until the rest shows up.
    let pendingLine = '';

    const handleLine = (line) => {
      const errorIndex = line.indexOf(ERROR_MARKER);
      if (errorIndex !== -1) {
        const message = line.slice(errorIndex + ERROR_MARKER.length).trim();
        if (message) errorText = message;
        return;
      }
      const index = line.indexOf(MARKER);
      if (index === -1) return;
      const raw = line.slice(index + MARKER.length).trim();
      if (!raw) return;
      let payload;
      try {
        payload = JSON.parse(raw);
      } catch (e) {
        return;
      }
      if (payload.stage === 'cancelled') {
        cancelledByUser = true;
      }
      onProgress(payload);
    };

    const onChunk = (chunk) => {
      const text = chunk.toString();
      stdout += text;
      pendingLine += text;
      const lines = pendingLine.split('\n');
      pendingLine = lines.pop();
      for (const line of lines) {
        handleLine(line);
      }
    };

    child.stdout.on('data', onChunk);
    child.stderr.on('data', (chunk) => {
      const text = chunk.toString();
      stderr += text;
      logTail(text);
    });

    child.on('error', (error) => {
      activeRun = null;
      if (error.code === 'ENOENT') {
        reject(new Error('pkexec is not installed. Install polkit to allow Rufus to write to USB devices.'));
        return;
      }
      reject(new Error(`Failed to start privileged helper: ${error.message}`));
    });

    child.on('close', (code, signal) => {
      activeRun = null;
      if (pendingLine) handleLine(pendingLine);
      const tail = readLogTail();
      const result = { code: code === null ? -1 : code, stdout, stderr };

      if (cancelledByUser) {
        reject(new Error('Operation cancelled'));
        return;
      }
      if (code === 0) {
        resolve(result);
        return;
      }
      if (code === 126 || code === 127) {
        reject(new Error('Authorization was denied, or the polkit agent is not available on this desktop session.'));
        return;
      }
      if (signal) {
        reject(new Error(`Privileged operation was terminated (${signal}).${tail ? ` ${tail}` : ''}`));
        return;
      }
      if (errorText) {
        reject(new Error(errorText));
        return;
      }
      reject(new Error(`Privileged operation failed (exit code ${code}).${tail ? ` ${tail}` : ''}`));
    });
  });
}

function logTail(text) {
  try {
    // Keep the log bounded: a failing wimlib run is chatty and this file is
    // only used to build the error message shown in the UI.
    if (fs.existsSync(OUTPUT_PATH) && fs.statSync(OUTPUT_PATH).size > 512 * 1024) {
      fs.truncateSync(OUTPUT_PATH, 0);
    }
    fs.appendFileSync(OUTPUT_PATH, text);
  } catch (e) {
    // best effort
  }
}

function readLogTail(limit = 400) {
  try {
    const text = fs.readFileSync(OUTPUT_PATH, 'utf8').trim();
    return text ? text.slice(-limit).replace(/\s+/g, ' ') : '';
  } catch (e) {
    return '';
  }
}

/**
 * Request cancellation of the running operation. The root script owns the
 * actual signals; we only drop the flag file it polls for.
 */
function cancelPrivileged() {
  try {
    fs.writeFileSync(CANCEL_PATH, 'cancel\n', { mode: 0o600 });
    return true;
  } catch (e) {
    return false;
  }
}

function clearCancel() {
  try {
    fs.unlinkSync(CANCEL_PATH);
  } catch (e) {
    // already gone
  }
}

function isRunning() {
  return activeRun !== null;
}

module.exports = {
  MARKER,
  STATE_DIR,
  marker,
  buildPreamble,
  runPrivileged,
  cancelPrivileged,
  clearCancel,
  isRunning
};
